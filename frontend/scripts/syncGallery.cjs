const fs = require('fs');
const path = require('path');

const galleryDir = path.join(__dirname, '..', 'public', 'gallery');
const jsonManifestFile = path.join(galleryDir, 'galleryManifest.json');
const tsManifestFile = path.join(__dirname, '..', 'src', 'data', 'localGalleryManifest.ts');

const validExts = ['.jpg', '.jpeg', '.png', '.webp', '.avif'];

function scanFolders() {
  if (!fs.existsSync(galleryDir)) {
    console.log('No gallery directory found at', galleryDir);
    return;
  }

  const manifest = {};
  const entries = fs.readdirSync(galleryDir, { withFileTypes: true });

  for (const entry of entries) {
    if (entry.isDirectory()) {
      const folderName = entry.name;
      const folderPath = path.join(galleryDir, folderName);
      const files = fs
        .readdirSync(folderPath)
        .filter((file) => validExts.includes(path.extname(file).toLowerCase()))
        .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }))
        .map((file) => `/gallery/${folderName}/${file}`);

      manifest[folderName] = files;
      console.log(`📁 ${folderName}: found ${files.length} images`);
    }
  }

  // 1. Write public JSON manifest
  fs.writeFileSync(jsonManifestFile, JSON.stringify(manifest, null, 2), 'utf8');

  // 2. Write TypeScript manifest for instant bundling
  const tsContent = `// Automatically generated by scripts/syncGallery.cjs
// Do not edit manually. Run 'npm run sync-gallery' to refresh.

export const localGalleryManifest: Record<string, string[]> = ${JSON.stringify(manifest, null, 2)};
`;
  fs.writeFileSync(tsManifestFile, tsContent, 'utf8');

  console.log(`\n✅ Generated manifests:\n- ${jsonManifestFile}\n- ${tsManifestFile}`);
}

scanFolders();
